#!/usr/bin/env python3
"""Bake .tack.phrase.json files into firmware user phrase slots for TACK LOOP.

Reads ./phrases/ from the source tree.

Writes/updates:
  firmware/src/tack/tack_phrases_user.c
  firmware/src/tack/tack_phrases_user.h

Max 8 user phrases. Qualities mapped to TACK_Q_* ints when the header is present;
otherwise stores string tags the loader maps at runtime.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # felucca-tack or tack58 stage
# Prefer being run from felucca-tack root
if (Path.cwd() / "firmware/src/tack").is_dir():
    ROOT = Path.cwd()

CANDIDATES = [ROOT / "phrases"]

QUALITY = {
    "maj": 0, "min": 1, "dim": 2, "aug": 3,
    "maj7": 4, "min7": 5, "dom7": 6, "halfdim": 7, "sus": 8, "sus2": 9,
}
RHYTHM = {"EVEN": 0, "WHOLE": 1, "HALF": 2, "QTR": 3, "SYNC": 4, "OFF": 5, "SPARSE": 6}

def load_phrases():
    files = []
    for d in CANDIDATES:
        if d.is_dir():
            files.extend(sorted(d.glob("*.tack.phrase.json")))
    # de-dupe by name, first wins
    seen, out = set(), []
    for f in files:
        try:
            data = json.loads(f.read_text())
        except Exception as e:
            print(f"skip {f}: {e}", file=sys.stderr)
            continue
        if data.get("format") != "tack-phrase/1":
            print(f"skip {f}: bad format", file=sys.stderr)
            continue
        key = data.get("name") or f.stem
        if key in seen:
            continue
        seen.add(key)
        out.append((key, data, f))
    return out[:8]

def c_str(s, n=16):
    s = re.sub(r'[^A-Za-z0-9 _+-]', '', str(s))[:n]
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    phrases = load_phrases()
    out_c = ROOT / "firmware/src/tack/tack_phrases_user.c"
    out_h = ROOT / "firmware/src/tack/tack_phrases_user.h"
    out_c.parent.mkdir(parents=True, exist_ok=True)

    h = '''/* Auto-generated by tools/tack_ingest_phrases.py — do not edit. */
#pragma once
#include <stdint.h>
#define TACK_USER_PHRASE_MAX 8
#define TACK_USER_CHORD_MAX 8
typedef struct {
  char name[17];
  uint16_t tempo;
  uint8_t style;   /* index into TACK_STYLE_NAME; 0xFF = keep */
  uint8_t rhythm;  /* EVEN..SPARSE */
  uint8_t root_pc; /* 0=C .. 11=B */
  uint8_t nch;
  uint8_t deg[TACK_USER_CHORD_MAX];
  uint8_t qual[TACK_USER_CHORD_MAX];
  uint8_t bars[TACK_USER_CHORD_MAX];
} tack_user_phrase_t;
extern const tack_user_phrase_t TACK_USER_PHRASE[TACK_USER_PHRASE_MAX];
extern const uint8_t TACK_USER_PHRASE_COUNT;
'''
    NOTE = {"C":0,"C#":1,"Db":1,"D":2,"D#":3,"Eb":3,"E":4,"F":5,"F#":6,"Gb":6,
            "G":7,"G#":8,"Ab":8,"A":9,"A#":10,"Bb":10,"B":11}

    # Style name → index left as 0xFF; runtime resolves by string table if available
    rows = []
    for i, (name, data, src) in enumerate(phrases):
        root = str(data.get("root") or "C")
        pc = NOTE.get(root, NOTE.get(root[:1].upper()+root[1:], 0))
        rhy = RHYTHM.get(str(data.get("rhythm") or "EVEN").upper(), 0)
        tempo = int(data.get("tempo") or 100)
        chords = data.get("chords") or []
        nch = min(8, len(chords))
        degs, quals, bars = [], [], []
        for c in chords[:8]:
            degs.append(int(c.get("degree", 0)) % 7)
            quals.append(QUALITY.get(str(c.get("quality") or "maj").lower(), 0))
            bars.append(max(1, int(c.get("bars") or 1)))
        while len(degs) < 8:
            degs.append(0); quals.append(0); bars.append(1)
        style_hint = str(data.get("styleHint") or "CLASSIC").upper()
        rows.append(
            f'  {{ .name = {c_str(name)}, .tempo = {tempo}, .style = 0xFF, '
            f'.rhythm = {rhy}, .root_pc = {pc}, .nch = {nch}, '
            f'.deg = {{{", ".join(map(str, degs))}}}, '
            f'.qual = {{{", ".join(map(str, quals))}}}, '
            f'.bars = {{{", ".join(map(str, bars))}}} }}, '
            f'/* {style_hint} from {src.name} */'
        )
    while len(rows) < 8:
        rows.append('  { .name = "", .tempo = 100, .style = 0xFF, .rhythm = 0, .root_pc = 0, .nch = 0, '
                    '.deg = {0}, .qual = {0}, .bars = {1} },')

    c = f'''/* Auto-generated by tools/tack_ingest_phrases.py — do not edit. */
#include "tack_phrases_user.h"
const uint8_t TACK_USER_PHRASE_COUNT = {len(phrases)};
const tack_user_phrase_t TACK_USER_PHRASE[TACK_USER_PHRASE_MAX] = {{
{chr(10).join(rows)}
}};
'''
    out_h.write_text(h)
    out_c.write_text(c)
    print(f"Wrote {out_h}")
    print(f"Wrote {out_c}  ({len(phrases)} phrases)")
    for name, data, src in phrases:
        print(f"  - {name}: {data.get('styleHint')} {data.get('rhythm')} ← {src}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
